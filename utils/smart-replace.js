/**
 * smartReplace 核心逻辑
 * 策略：长串优先 → 语义明确优先 → 通用兜底
 * 替换原则：
 *   - 从长到短匹配（18X → 12X → 8X → 4X → 3X）
 *   - 带字段名的优先于裸 X 串
 *   - lookahead 排除歧义字符
 */

function doSmartReplace(content, categoryName) {
  var now = new Date();
  var dateStr = now.getFullYear() + '年'
    + String(now.getMonth() + 1).padStart(2, '0') + '月'
    + String(now.getDate()).padStart(2, '0') + '日';

  var r = content;

  // ══════════════════════════════════════════════════════
  // 1. 日期
  // ══════════════════════════════════════════════════════
  r = r.replace(/XXXX年XX月XX日/g, dateStr);

  // ══════════════════════════════════════════════════════
  // 2. 18位身份证号/统一社会信用代码
  // ══════════════════════════════════════════════════════
  r = r.replace(/XXXXXXXXXXXXXXXXXX/g, '（示例：110101199001011234）');
  r = r.replace(/统一社会信用代码：X{8,}/g, '统一社会信用代码：（示例：91350100M000100YG）');

  // ══════════════════════════════════════════════════════
  // 3. 12位电话号码
  // ══════════════════════════════════════════════════════
  r = r.replace(/XXXXXXXXXXXX/g, '（示例：075512345678）');

  // ══════════════════════════════════════════════════════
  // 4. 带分隔电话 XXXX-XXXXXXXX
  // ══════════════════════════════════════════════════════
  r = r.replace(/XXXX-XXXXXXXX/g, '（示例：0755-12345678）');

  // ══════════════════════════════════════════════════════
  // 5. 带字段名的 8X（必须在通用 8X 之前）
  // ══════════════════════════════════════════════════════
  var fields8x = [
    '拍卖标的', '展示地点', '报名地点', '网址', '标的名称', '资产名称', '资产位置',
    '具体内容', '事件描述', '问题说明', '违约情况', '损害描述', '道歉原因', '致歉理由',
    '联系邮箱', '联系地址', '通信地址', '家庭住址', '办公地址', '注册地址',
    '许可证编号', '备案编号', '合同编号', '证件编号', '证书编号', '权证编号', '设备编号',
    '开户行', '开户银行', '银行账号', '银行账户', '收款账号', '付款账号', '账号'
  ];
  fields8x.forEach(function(f) {
    r = r.replace(new RegExp(f + '：XXXXXXXX', 'g'), f + '：（示例：请填写）');
  });

  // 特殊字段
  r = r.replace(/票据号码：XXXXXXXX/g, '票据号码：（示例：12345678）');
  r = r.replace(/保证金：XXXXXXXX/g, '保证金：（示例：5万元）');
  r = r.replace(/参考价：XXXXXXXX/g, '参考价：（示例：10万元）');
  r = r.replace(/起拍价：XXXXXXXX/g, '起拍价：（示例：8万元）');
  r = r.replace(/成交价：XXXXXXXX/g, '成交价：（示例：12万元）');

  // ══════════════════════════════════════════════════════
  // 6. 语义明确的 8X 模式（带上下文）
  // ══════════════════════════════════════════════════════
  r = r.replace(/XXXXXXXX（平台\/场合）/g, '（示例：XX平台）（平台\/场合）');
  r = r.replace(/XXXXXXXX（事件）/g, '（示例：XX事件）（事件）');
  r = r.replace(/XXXXXXXX（作品/g, '（示例：具体作品）（作品');
  r = r.replace(/XXXXXXXX元/g, '（示例：XX万元）元');
  r = r.replace(/XXXXXXXX展示/g, '（示例：XX地点）展示');
  r = r.replace(/发布了关于XXXXXXXX的/g, '发布了关于（示例：具体内容）的');
  r = r.replace(/在XXXXXXXX发布了/g, '在（示例：XX平台）发布了');
  r = r.replace(/在XXXXXXXX中/g, '在（示例：XX事件）中');
  r = r.replace(/就XXXXXXXX事件/g, '就（示例：XX）事件');
  r = r.replace(/XXXXXXXX事件/g, '（示例：XX）事件');
  r = r.replace(/对XXXX造成了/g, '对（示例：XX）造成了');
  r = r.replace(/误解了XXXX/g, '误解了（示例：XX）');
  r = r.replace(/误伤了XXXX/g, '误伤了（示例：XX）');

  // ══════════════════════════════════════════════════════
  // 7. 通用 8X 兜底（排除年、数字、中文）
  // ══════════════════════════════════════════════════════
  r = r.replace(/XXXXXXXX(?![年\d一-龥])/g, '（示例：请填写）');

  // ══════════════════════════════════════════════════════
  // 8. 带字段名的 4X
  // ══════════════════════════════════════════════════════
  r = r.replace(/金额：XXXX/g, '金额：（示例：1000）');
  r = r.replace(/地址：XXXX/g, '地址：（示例：XX路XX号）');
  r = r.replace(/案号：XXXX/g, '案号：（示例：2024）');

  // ══════════════════════════════════════════════════════
  // 9. XXXX公司 / XXX公司（必须在通用 4X/3X 之前）
  // ══════════════════════════════════════════════════════
  r = r.replace(/XXXX公司/g, '（示例：XX公司）有限公司');
  r = r.replace(/XXXX有限公司/g, '（示例：XX公司）有限公司');
  r = r.replace(/XXXX人民法院/g, '（示例：XX市）人民法院');
  r = r.replace(/XXX公司(?!\d)/g, '（示例：XX公司）');
  r = r.replace(/XXX有限公司/g, '（示例：XX）有限公司');

  // ══════════════════════════════════════════════════════
  // 10. 通用 4X 兜底（排除年、数字、中文）
  // ══════════════════════════════════════════════════════
  r = r.replace(/XXXX(?![年\d一-龥])/g, '（示例：XX）');

  // ══════════════════════════════════════════════════════
  // 11. 姓名标签（XXX + 称呼）
  // ══════════════════════════════════════════════════════
  var nameLabels = [
    '声明人', '致歉人', '道歉人', '联系人', '法定代表人', '申请人', '被申请人',
    '当事人', '负责人', '出借人', '借款人', '保证人', '担保人', '债权人', '债务人',
    '受让人', '转让人', '原告', '被告', '第三人', '委托人', '受托人', '继承人',
    '被继承人', '遗赠人', '受遗赠人', '买受人', '出卖人', '出租人', '承租人',
    '新郎', '新娘', '寿星', '学子', '学生', '家长', '家人', '祝福人'
  ];
  nameLabels.forEach(function(f) {
    r = r.replace(new RegExp(f + '：XXX', 'g'), f + '：（示例：张三）');
  });

  // 姓名前后缀
  r = r.replace(/本人XXX/g, '本人（示例：张三）');
  r = r.replace(/被告XXX/g, '被告（示例：张三）');
  r = r.replace(/XXX先生/g, '（示例：张三）先生');
  r = r.replace(/XXX女士/g, '（示例：张三）女士');
  r = r.replace(/亲爱的XXX/g, '亲爱的（示例：张三）');
  r = r.replace(/致我最好的朋友XXX/g, '致我最好的朋友（示例：张三）');
  r = r.replace(/永远爱你的：XXX/g, '永远爱你的：（示例：张三）');

  // ══════════════════════════════════════════════════════
  // 12. 通用 XXX 兜底（排除数字、中文，且不被其他X包围）
  // ══════════════════════════════════════════════════════
  r = r.replace(/(?<![X])XXX(?![X年\d一-龥])/g, '（示例：张三）');

  return r;
}

module.exports = { doSmartReplace: doSmartReplace };
