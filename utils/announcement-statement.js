    '送达公告': '现依法向XXX送达...，自公告之日起经过六十日即视为送达。',
    '通知送达公告': '通知内容：...，当事人应在规定期限内办理，逾期承担相应法律后果。',
    '催告送达': '催告事项：...，请当事人自收到本公告之日起XX日内依法履行义务，逾期将承担相应责任。',
